// "Частые вопросы" в разделе "Справка": ответы на то, о чём обычно спрашивают автора.
// Каждый ответ говорит, что сделать, и по возможности ведёт кнопкой в нужный раздел.
import type { PublicSettings } from '@shared/settings'

/** Разделы, в которые ведут кнопки из ответов. */
export type HelpTarget = 'main' | 'voice' | 'sound' | 'filters' | 'mutes' | 'connection'

interface Item {
  q: string
  a: React.JSX.Element
  /** Кнопка под ответом: раздел и подпись. */
  to?: [HelpTarget, string]
}

function items(s: PublicSettings): Item[] {
  const delay = (s.tts.chatDelayMs / 1000).toLocaleString('ru-RU')
  const key = (v: string): string => v || 'не назначено'
  return [
    {
      q: 'Сообщение в чате есть, а звука нет',
      a: (
        <>
          <p>Пройдите по порядку:</p>
          <ol>
            <li>
              Справа от ника в чате написано, что стало с сообщением. "отклонено" и причина:
              сообщение не прошло фильтр. Подписи нет: это обычное сообщение без префикса, оно и не
              должно звучать.
            </li>
            <li>
              Вверху окна полоса "Нет ключа Fish Audio": добавьте ключ в разделе "Подключение".
            </li>
            <li>
              Вверху полоса "Озвучка остановилась": в ней написана причина. Исправьте её и нажмите
              "Продолжить".
            </li>
            <li>Кнопка внизу справа называется "Продолжить": озвучка на паузе, нажмите её.</li>
            <li>Громкость внизу окна не на нуле.</li>
            <li>
              В разделе "Звук" выбрано то устройство, которое вы слушаете. В режиме "OBS" там должно
              быть написано "OBS подключён".
            </li>
          </ol>
          <p>
            Быстрее всего нажать "Проверить всё" в разделе "Подключение": программа пройдёт эти шаги
            сама.
          </p>
        </>
      ),
      to: ['connection', 'Открыть "Подключение"']
    },
    {
      q: 'Зрители не слышат озвучку',
      a: (
        <>
          <p>Зависит от того, куда идёт звук (раздел "Звук"):</p>
          <ul>
            <li>
              "Динамики или наушники": озвучка звучит как любой звук компьютера. OBS должен его
              записывать: в микшере OBS это "Звук рабочего стола".
            </li>
            <li>
              "Виртуальный кабель": в OBS нужен источник "Захват входного аудиопотока" с этим
              кабелем.
            </li>
            <li>
              "OBS: источник "Браузер"": в OBS нужен источник "Браузер" с адресом из раздела "Звук"
              и галка "Управлять звуком через OBS".
            </li>
          </ul>
        </>
      ),
      to: ['sound', 'Открыть "Звук"']
    },
    {
      q: 'Зрители слышат озвучку дважды',
      a: (
        <p>
          Звук попадает в OBS двумя путями сразу. Обычно это источник "Браузер" или кабель и
          вдобавок звук рабочего стола. Оставьте один путь. Если в разделе "Звук" написано
          "источников: 2", удалите в OBS второй источник "Браузер". Если включено "Дублировать в
          наушники", проверьте, что это не то же устройство, которое записывает OBS.
        </p>
      ),
      to: ['sound', 'Открыть "Звук"']
    },
    {
      q: 'Что бесплатно, а что платно',
      a: (
        <>
          <p>
            Сама программа бесплатная. Голос делает сервис Fish Audio. У него есть бесплатная модель
            s2.1-pro-free: она выбрана в программе сразу, карта для неё не нужна.
          </p>
          <p>
            Платные модели берут деньги с баланса на fish.audio по объёму текста: обычное сообщение
            чата стоит около $0.002. Чтобы не потратить лишнего, в разделе "Голос" есть лимит трат в
            день. По документации Fish у бесплатной модели нет отдельных ограничений; одновременно
            Fish готовит не больше 5 фраз, программа отправляет по 2.
          </p>
        </>
      ),
      to: ['voice', 'Открыть "Голос"']
    },
    {
      q: 'Почему сообщение звучит не сразу',
      a: (
        <p>
          Сообщение из чата ждёт {delay} с: если за это время бот или модератор его удалит, оно не
          прозвучит. Ещё 1-3 секунды Fish готовит звук. Задержку можно изменить в разделе "Звук",
          поле "Задержка перед озвучкой". Когда сообщений много, они звучат по очереди: порядок
          виден справа на экране "Чат и очередь".
        </p>
      ),
      to: ['sound', 'Открыть "Звук"']
    },
    {
      q: 'Что происходит с удалёнными сообщениями',
      a: (
        <p>
          Сообщение, которое удалил модератор или бот, не звучит. Если оно уже звучит, озвучка
          обрывается. То же при бане и таймауте зрителя и при очистке чата. Повторить такое
          сообщение из истории или озвучить его вручную нельзя.
        </p>
      )
    },
    {
      q: 'Как быстро остановить озвучку во время стрима',
      a: (
        <>
          <ul>
            <li>
              Пауза: большая кнопка внизу справа или{' '}
              <span className="mono">{key(s.hotkeys.pause)}</span>.
            </li>
            <li>
              Пропустить то, что звучит: <span className="mono">{key(s.hotkeys.skip)}</span>.
            </li>
            <li>
              Выключить озвучку совсем: <span className="mono">{key(s.hotkeys.toggle)}</span>.
            </li>
          </ul>
          <p>
            Клавиши работают и из игры, меняются в разделе "Звук". Замолчать одного зрителя: кнопка
            мьюта у его сообщения. Запретить слова: раздел "Фильтры", "Стоп-слова".
          </p>
        </>
      ),
      to: ['filters', 'Открыть "Фильтры"']
    },
    {
      q: 'Как объяснить зрителям, как пользоваться',
      a: (
        <p>
          Во вкладке "Теги эмоций" внизу есть готовый текст для чата с вашим префиксом. Скопируйте
          его в команду бота или в панель под стримом.
        </p>
      )
    },
    {
      q: 'Как добавить свой голос',
      a: (
        <p>
          Откройте голос на fish.audio: чужой из каталога или свой, записанный там же. Скопируйте
          адрес страницы из браузера и вставьте в разделе "Голос" в поле под избранными голосами.
          Голос добавится и сразу выберется.
        </p>
      ),
      to: ['voice', 'Открыть "Голос"']
    },
    {
      q: 'Чего программа пока не умеет',
      a: (
        <>
          <ul>
            <li>озвучивать донаты, подписки, рейды и новых фолловеров;</li>
            <li>работать с YouTube, Kick и VK Play;</li>
            <li>читать несколько каналов сразу;</li>
            <li>проверять, фолловер ли зритель.</li>
          </ul>
          <p>
            Озвучка за баллы канала работает: раздел "Фильтры", настройка "Что запускает озвучку".
          </p>
        </>
      )
    },
    {
      q: 'Как перенести программу на другой компьютер',
      a: (
        <p>
          Скопируйте папку программы целиком. Настройки, голоса и списки переедут вместе с ней. Ключ
          Fish придётся ввести заново: он зашифрован под вашу учётную запись Windows и на другом
          компьютере не читается. То же после переустановки Windows.
        </p>
      )
    },
    {
      q: 'Как удалить программу',
      a: (
        <p>
          Закройте программу и удалите её папку. Больше нигде на компьютере она ничего не хранит.
          Исключение: если программа лежала там, куда нельзя записывать (например, в Program Files),
          настройки лежат в папке из раздела "Подключение", блок "Данные программы".
        </p>
      )
    },
    {
      q: 'Обновление не ставится',
      a: (
        <p>
          В окне обновления нажмите "Повторить": скачивание продолжится с того же места. Не
          помогает: там же есть ссылка "скачайте новую версию вручную". Распакуйте архив поверх
          папки программы, настройки и ключ сохранятся. Иногда замене файлов мешает антивирус. Тогда
          программа возвращает прежнюю версию и предлагает обновление при следующем запуске.
        </p>
      )
    },
    {
      q: 'Windows или антивирус ругается на программу',
      a: (
        <p>
          У программы пока нет платной цифровой подписи, поэтому Windows показывает "Windows
          защитила ваш компьютер". Нажмите "Подробнее", затем "Выполнить в любом случае". Архив
          можно проверить на virustotal.com: в релизе рядом с ним лежит файл с контрольной суммой.
        </p>
      )
    },
    {
      q: 'Что программа отправляет в интернет',
      a: (
        <>
          <ul>
            <li>Twitch: читает чат без входа в ваш аккаунт.</li>
            <li>Fish Audio: текст сообщений для озвучки и ваш ключ.</li>
            <li>7TV, BTTV и FFZ: списки эмоутов канала, чтобы не читать их вслух.</li>
            <li>GitHub: проверка новой версии.</li>
            <li>
              Сервер отзывов: только когда вы сами нажали "Отправить" в окне "Сообщить о проблеме".
              Перед отправкой виден весь текст.
            </li>
          </ul>
          <p>Статистику программа не собирает.</p>
        </>
      )
    }
  ]
}

export function Faq(props: {
  s: PublicSettings
  go: (v: HelpTarget) => void
  /** Перейти на вкладку "Теги эмоций" (там шпаргалка для зрителей). */
  onTags: () => void
}): React.JSX.Element {
  return (
    <section className="group faq">
      <p className="muted small">
        Нажмите на вопрос, чтобы открыть ответ. Не нашли свой: кнопка "Сообщить о проблеме" слева
        внизу.
      </p>
      {items(props.s).map((it) => (
        <details key={it.q}>
          <summary>{it.q}</summary>
          <div className="faq-a">
            {it.a}
            {it.to && <button onClick={() => props.go(it.to?.[0] ?? 'main')}>{it.to[1]}</button>}
            {it.q.startsWith('Как объяснить') && (
              <button onClick={props.onTags}>Открыть "Теги эмоций"</button>
            )}
          </div>
        </details>
      ))}
    </section>
  )
}
