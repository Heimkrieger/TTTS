// Проверка регулярных выражений, которые стример пишет в стоп-слова (/шаблон/флаги).
// Выражения вида (а+)+ или (а|а)* на длинном сообщении перебирают варианты так долго, что
// программа зависает на секунды (катастрофический перебор). Такие отказываемся сохранять.

/** Группа, внутри которой есть повтор (+, *, {n,}), и после неё снова повтор: (а+)+, (\w*)*. */
const NESTED_REPEAT = /\((?:[^()\\]|\\.)*(?:[+*]|\{\d+,\d*\})(?:[^()\\]|\\.)*\)(?:[+*]|\{\d+,)/
/** Группа с вариантами через |, которая повторяется: (а|аа)+. */
const REPEATED_ALTERNATION = /\((?:[^()\\]|\\.)*\|(?:[^()\\]|\\.)*\)(?:[+*]|\{\d+,)/

/** true - выражение опасно для производительности. */
export function isRiskyRegex(source: string): boolean {
  return NESTED_REPEAT.test(source) || REPEATED_ALTERNATION.test(source)
}
